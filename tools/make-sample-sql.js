// Writes db/sample-data.sql: the fictional sample data as INSERT statements for db/schema.sql.
// It is the format reference for the real data file. Run from the repo root:
//   node tools/make-sample-sql.js
const fs = require('fs');
const path = require('path');
const vm = require('vm');

const root = path.join(__dirname, '..');
const ctx = {};
vm.createContext(ctx);
vm.runInContext(fs.readFileSync(path.join(root, 'js/data.js'), 'utf8') + '\nthis.makeSampleData = makeSampleData;', ctx);
const d = ctx.makeSampleData();

const q = (v) => {
  if (v === null || v === undefined || v === '') return 'null';
  if (v instanceof Date || Object.prototype.toString.call(v) === '[object Date]') {
    const x = new Date(v);
    return `'${x.getFullYear()}-${String(x.getMonth() + 1).padStart(2, '0')}-${String(x.getDate()).padStart(2, '0')}'`;
  }
  if (typeof v === 'number') return String(v);
  return `'${String(v).replace(/'/g, "''")}'`;
};
const rows = (table, cols, list, tail = '') =>
  list.length ? `insert into ${table} (${cols.join(', ')}) values\n${list.map((r) => `  (${r.map(q).join(', ')})`).join(',\n')}${tail};\n` : '';

const DEPT_IDS = { 'Management': 1, 'Sales & Marketing': 2, 'Company Formation': 3, 'PRO & Visa': 4, 'Banking': 5, 'Accounting & Tax': 6, 'Loans & Mortgage': 7, 'Advisory': 8, 'HR & Admin': 9 };
const uuid = (i) => `00000000-0000-4000-8000-${String(i).padStart(12, '0')}`;

const services = d._services.map((s, i) => ({ ...s, id: i + 1 }));
const serviceId = (dept, name) => (services.find((s) => s.Service === name && (!dept || s.Department === dept)) || {}).id || null;
const staff = d.Team.map((m, i) => ({ ...m, id: uuid(i + 1) }));
const staffId = (name) => (staff.find((s) => s.Staff === name) || {}).id || null;
const clientId = (ref) => Number(String(ref).replace(/\D/g, '')) || null;
const campaignNames = [...new Set(d.Campaigns.map((c) => c.Campaign))];
const campaignId = (name) => (name ? campaignNames.indexOf(name) + 1 || null : null);
const today = new Date(); today.setHours(0, 0, 0, 0);
const addDays = (x, n) => { const y = new Date(x); y.setDate(y.getDate() + n); return y; };

let out = `-- AB Capital Services: SAMPLE data (fictional) for db/schema.sql.
-- Use this file as the format for the real data file. Load order matters (references).
-- Real data files must never be committed to the public repo; .gitignore blocks *.sql except this file and schema.sql.
-- Generated by tools/make-sample-sql.js on ${q(today)}.

`;
out += rows('services', ['id', 'department_id', 'name', 'default_fee'], services.map((s) => [s.id, DEPT_IDS[s.Department], s.Service, s.Fee]));
out += `select setval('services_id_seq', (select max(id) from services));\n\n`;
out += rows('staff', ['id', 'full_name', 'department_id', 'role', 'job_title'], staff.map((s) => [s.id, s.Staff, DEPT_IDS[s.Department], s.Department === 'Management' ? 'manager' : 'staff', s.Role]));
out += rows('staff_leave', ['staff_id', 'starts_on', 'ends_on'], staff.filter((s) => s.OnLeave === 'Y').map((s) => [s.id, addDays(today, -1), addDays(today, 5)]));
out += '\n';
out += rows('clients', ['id', 'ref', 'name', 'company', 'jurisdiction', 'licence_no', 'trn', 'start_date'], d.Clients.map((c) => [clientId(c.ClientID), c.ClientID, c.Name, c.Company, c.Jurisdiction, c.LicenceNo, c.TRN, c.StartDate]));
out += `select setval('clients_id_seq', (select max(id) from clients));\n\n`;
const campPlatform = Object.fromEntries(d.Campaigns.map((c) => [c.Campaign, c.Platform]));
out += rows('campaigns', ['id', 'name', 'platform'], campaignNames.map((n, i) => [i + 1, n, campPlatform[n]]));
out += `select setval('campaigns_id_seq', (select max(id) from campaigns));\n`;
out += rows('campaign_spend', ['campaign_id', 'month', 'spend_aed', 'impressions', 'clicks'], d.Campaigns.map((c) => [campaignId(c.Campaign), c.Month, c.SpendAED, c.Impressions, c.Clicks]));
out += '\n';
out += rows('leads', ['ref', 'created_on', 'source', 'campaign_id', 'client_name', 'service_id', 'value_aed', 'status', 'owner_id'],
  d.Leads.map((l) => [l.LeadID, l.Date, l.Source, campaignId(l.Campaign), l.ClientName, serviceId(null, l.Service), l.ValueAED, l.Status, staffId(l.Owner)]));
out += '\n';
out += rows('cases', ['ref', 'client_id', 'service_id', 'stage', 'assignee_id', 'opened_on', 'due_on', 'closed_on', 'fee_aed', 'status'],
  d.Cases.map((c) => [c.CaseID, clientId(c.ClientID), serviceId(c.Department, c.Service), c.Stage, staffId(c.Assignee), c.OpenedOn, c.DueDate, c.ClosedOn, c.FeeAED, c.Status]));
out += '\n';
out += rows('expiries', ['client_id', 'type', 'number', 'expiry_date'], d.Expiries.map((e) => [clientId(e.ClientID), e.Type, e.Number, e.ExpiryDate]));
out += rows('bank_applications', ['client_id', 'bank', 'applied_on', 'status', 'rejection_reason'], d.Banking.map((b) => [clientId(b.ClientID), b.Bank, b.AppliedOn, b.Status, b.RejectionReason]));
out += rows('tax_filings', ['client_id', 'type', 'period', 'due_on', 'filed_on'],
  d.TaxCalendar.map((t) => [clientId(t.ClientID), t.Type, t.Period, t.DueDate, t.Filed === 'Y' ? addDays(t.DueDate, -3) : null]), '\non conflict (client_id, type, period) do nothing');
out += '\n';
out += rows('finance_monthly', ['month', 'revenue_aed', 'expenses_aed', 'collected_aed', 'vat_payable_aed'], d.Finance.map((f) => [f.Month, f.RevenueAED, f.ExpensesAED, f.CollectedAED, f.VATPayableAED]));
out += rows('receivables', ['client_name', 'invoice_no', 'invoice_date', 'due_on', 'amount_aed'], d.Receivables.map((r) => [r.ClientName, r.InvoiceNo, r.InvoiceDate, r.DueDate, r.AmountAED]));
out += rows('bank_balances', ['bank', 'account', 'balance_aed', 'as_of'], d.BankBalances.map((b) => [b.Bank, b.Account, b.BalanceAED, b.AsOf]));

fs.writeFileSync(path.join(root, 'db/sample-data.sql'), out);
console.log(`db/sample-data.sql written (${out.length} bytes)`);
